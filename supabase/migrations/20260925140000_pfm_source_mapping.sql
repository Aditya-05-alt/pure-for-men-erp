-- Raw source/medium for Pure for Men (page views + product views)
CREATE OR REPLACE FUNCTION public.get_pfm_raw_source_medium_traffic(
  p_from date,
  p_to date,
  p_client_id text DEFAULT '001'
)
RETURNS TABLE (
  raw_source text,
  raw_medium text,
  raw_channel text,
  page_views bigint,
  vdp_views bigint
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT
    COALESCE(NULLIF(TRIM(d.source), ''), '(direct)') AS raw_source,
    COALESCE(NULLIF(TRIM(d.medium), ''), '(none)') AS raw_medium,
    COALESCE(NULLIF(TRIM(d.channel), ''), '(not set)') AS raw_channel,
    COALESCE(SUM(d.views), 0)::bigint AS page_views,
    COALESCE(
      SUM(d.views) FILTER (WHERE public.is_pfm_product_page_path(d.page_path)),
      0
    )::bigint AS vdp_views
  FROM public.chipper_pfm_ga4_data d
  WHERE d.client_id = p_client_id
    AND d.report_date >= p_from
    AND d.report_date <= p_to
    AND COALESCE(d.page_path, '') NOT ILIKE '%/web-pixels%'
  GROUP BY 1, 2, 3
  HAVING COALESCE(SUM(d.views), 0) > 0
  ORDER BY page_views DESC;
$$;

REVOKE ALL ON FUNCTION public.get_pfm_raw_source_medium_traffic(date, date, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.get_pfm_raw_source_medium_traffic(date, date, text) TO anon, authenticated, service_role;
