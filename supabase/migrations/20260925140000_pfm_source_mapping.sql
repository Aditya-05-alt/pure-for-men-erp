-- Source mapping tables + PFM raw source/medium traffic for Product Views

CREATE TABLE IF NOT EXISTS public.smart_source_mapping_channels (
  id text PRIMARY KEY,
  name text NOT NULL,
  color text NOT NULL DEFAULT '#94a3b8',
  sort_order integer NOT NULL DEFAULT 100,
  is_unmapped boolean NOT NULL DEFAULT false,
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.smart_source_mapping_rules (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  raw_source text NOT NULL,
  raw_medium text NOT NULL,
  channel_id text NOT NULL REFERENCES public.smart_source_mapping_channels (id) ON DELETE CASCADE,
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (raw_source, raw_medium)
);

CREATE INDEX IF NOT EXISTS idx_smart_source_mapping_rules_channel
  ON public.smart_source_mapping_rules (channel_id);

ALTER TABLE public.smart_source_mapping_channels ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.smart_source_mapping_rules ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS smart_source_mapping_channels_read ON public.smart_source_mapping_channels;
CREATE POLICY smart_source_mapping_channels_read
  ON public.smart_source_mapping_channels FOR SELECT TO anon, authenticated
  USING (true);

DROP POLICY IF EXISTS smart_source_mapping_channels_write ON public.smart_source_mapping_channels;
CREATE POLICY smart_source_mapping_channels_write
  ON public.smart_source_mapping_channels FOR ALL TO anon, authenticated, service_role
  USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS smart_source_mapping_rules_read ON public.smart_source_mapping_rules;
CREATE POLICY smart_source_mapping_rules_read
  ON public.smart_source_mapping_rules FOR SELECT TO anon, authenticated
  USING (true);

DROP POLICY IF EXISTS smart_source_mapping_rules_write ON public.smart_source_mapping_rules;
CREATE POLICY smart_source_mapping_rules_write
  ON public.smart_source_mapping_rules FOR ALL TO anon, authenticated, service_role
  USING (true) WITH CHECK (true);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.smart_source_mapping_channels TO anon, authenticated, service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.smart_source_mapping_rules TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON SEQUENCE public.smart_source_mapping_rules_id_seq TO anon, authenticated, service_role;

